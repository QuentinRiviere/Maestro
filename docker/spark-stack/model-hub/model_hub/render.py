"""Render llama-swap.yaml = hand-written llama-swap.base.yaml + models.yml `serve:` entries.

The base file owns everything global: macros (it must define `llama-server`
and should define `models`), apiKeys, groups, hooks, peers and hand-written
models such as Maestro's `maestro-worker` lease. Managed entries only add
models, group memberships and preloads; they never replace a base key.
The result is validated against llama-swap's JSON schema before it is
written atomically (previous file kept as llama-swap.yaml.bak).
"""
from __future__ import annotations

import copy
import difflib
import json
import os
from typing import Callable

import jsonschema
import yaml

from . import registry

SCHEMA_PATH = os.path.join(os.path.dirname(__file__), "vendor", "llama-swap-config-schema.json")
DEFAULT_MODELS_ROOT = "/models"

GENERATED_HEADER = """\
# yaml-language-server: $schema=https://raw.githubusercontent.com/mostlygeek/llama-swap/refs/heads/main/config-schema.json
# GENERATED by the Spark model hub: do not edit. Edit llama-swap.base.yaml
# (global settings, groups, peers, hand-written models) or the `serve:`
# sections of models.yml (or the hub's UI), then re-render.
"""


class RenderError(ValueError):
    pass


_schema_cache: dict | None = None


def schema() -> dict:
    global _schema_cache
    if _schema_cache is None:
        with open(SCHEMA_PATH, encoding="utf-8") as handle:
            _schema_cache = json.load(handle)
    return _schema_cache


def validate(config: dict) -> list[str]:
    validator = jsonschema.Draft7Validator(schema())
    return [f"{'/'.join(str(p) for p in err.absolute_path) or '<root>'}: {err.message}"
            for err in sorted(validator.iter_errors(config), key=lambda e: list(map(str, e.absolute_path)))]


def load_base(path: str) -> dict:
    with open(path, encoding="utf-8") as handle:
        base = yaml.safe_load(handle) or {}
    if not isinstance(base, dict):
        raise RenderError(f"{path}: expected a mapping")
    return base


def _groups(config: dict) -> dict:
    """The group table the base uses (routing.router.settings.groups or legacy groups)."""
    routing = config.get("routing") or {}
    router = routing.get("router") or {}
    if router.get("use") == "matrix" or "matrix" in config:
        raise RenderError("managed models need group routing; the base uses the matrix router")
    if "groups" in config:
        if config["groups"] is None:
            config["groups"] = {}
        return config["groups"]
    config.setdefault("routing", {}).setdefault("router", {}).setdefault("use", "group")
    settings = config["routing"]["router"].setdefault("settings", {})
    if settings.get("groups") is None:
        settings["groups"] = {}
    return settings["groups"]


def base_groups(base: dict) -> dict:
    try:
        return copy.deepcopy(_groups(copy.deepcopy(base)))
    except RenderError:
        return {}


def build_cmd(entry: dict, serve: dict, models_root: str) -> str:
    repo = entry["repo"]
    lines = ["${llama-server}", f"--model {models_root}/{repo}/{serve['model']}"]
    if serve.get("mmproj"):
        lines.append(f"--mmproj {models_root}/{repo}/{serve['mmproj']}")
    sizing = []
    if serve.get("ctx_size"):
        sizing.append(f"--ctx-size {serve['ctx_size']}")
    sizing.append(f"--parallel {serve['parallel']}")
    lines.append(" ".join(sizing))
    if serve.get("mtp"):
        lines.append(f"--spec-type draft-mtp --spec-draft-n-max {serve['mtp_draft_n_max']}")
    if serve.get("extra_args"):
        lines.append(" ".join(serve["extra_args"]))
    return "\n".join(lines) + "\n"


def render(base: dict, entries: list[dict],
           available: Callable[[str, str], bool] | None = None) -> tuple[dict, list[str]]:
    """Return (config, warnings). Raises RenderError on conflicts or schema errors."""
    config = copy.deepcopy(base)
    warnings: list[str] = []
    macros = config.get("macros") or {}
    if "llama-server" not in macros:
        raise RenderError("llama-swap.base.yaml must define the `llama-server` macro")
    models_root = "${models}" if "models" in macros else DEFAULT_MODELS_ROOT
    if config.get("models") is None:
        config["models"] = {}
    models = config["models"]
    taken = set(models)
    for model in models.values():
        taken.update((model or {}).get("aliases") or [])
    for peer in (config.get("peers") or {}).values():
        taken.update((peer or {}).get("models") or [])
    groups = None
    for entry in entries:
        serve = entry.get("serve")
        if not serve:
            continue
        serve = registry.normalize_serve(serve)
        if not serve["enabled"]:
            continue
        repo = entry["repo"]
        files = [serve["model"]] + ([serve["mmproj"]] if serve.get("mmproj") else [])
        if available is not None:
            missing = [f for f in files if not available(repo, f)]
            if missing:
                warnings.append(f"{serve['id']}: not mapped, files not installed: {', '.join(missing)}")
                continue
        for name in [serve["id"], *serve["aliases"]]:
            if name in taken:
                raise RenderError(f"{serve['id']}: name '{name}' is already used in llama-swap.base.yaml "
                                  "or by another managed model")
            taken.add(name)
        if serve.get("mtp") and (serve.get("mmproj") or serve["parallel"] > 1):
            warnings.append(f"{serve['id']}: llama.cpp model cards (May 2026) say MTP did not support "
                            "--mmproj or --parallel > 1 yet; check llama-server's log if it fails to load")
        model = {}
        if serve.get("name"):
            model["name"] = serve["name"]
        model["description"] = f"{repo}@{str(entry.get('revision', ''))[:12]} (managed by model hub)"
        model["cmd"] = build_cmd(entry, serve, models_root)
        model["ttl"] = serve["ttl"]
        if serve["aliases"]:
            model["aliases"] = list(serve["aliases"])
        if serve["unlisted"]:
            model["unlisted"] = True
        models[serve["id"]] = model
        if groups is None:
            groups = _groups(config)
        group = groups.get(serve["group"])
        if group is None:
            group = groups[serve["group"]] = {"swap": True, "exclusive": False, "members": []}
            warnings.append(f"group '{serve['group']}' created (swap: true, exclusive: false); "
                            "define it in llama-swap.base.yaml to control it")
        group.setdefault("members", [])
        if group["members"] is None:
            group["members"] = []
        if serve["id"] not in group["members"]:
            group["members"].append(serve["id"])
        if serve["preload"]:
            preload = config.setdefault("hooks", {}).setdefault("on_startup", {})
            if preload.get("preload") is None:
                preload["preload"] = []
            if serve["id"] not in preload["preload"]:
                preload["preload"].append(serve["id"])
    errors = validate(config)
    if errors:
        raise RenderError("rendered config fails llama-swap's schema: " + "; ".join(errors[:5]))
    return config, warnings


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def dump(config: dict) -> str:
    return GENERATED_HEADER + "\n" + yaml.dump(config, Dumper=_Dumper, sort_keys=False, allow_unicode=True,
                                               width=200, default_flow_style=False)


def diff(old_text: str, new_text: str, path: str = "llama-swap.yaml") -> str:
    return "".join(difflib.unified_diff(old_text.splitlines(keepends=True), new_text.splitlines(keepends=True),
                                        fromfile=f"{path} (current)", tofile=f"{path} (new)"))


def read_text(path: str) -> str:
    if not os.path.exists(path):
        return ""
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def write(path: str, text: str) -> bool:
    """Atomic write with a .bak of the previous file. False when unchanged."""
    if read_text(path) == text:
        return False
    with registry.LOCK:
        registry.atomic_write(path, text, backup=True)
    return True


def render_files(base_path: str, models_path: str, out_path: str,
                 available: Callable[[str, str], bool] | None = None, dry_run: bool = False) -> dict:
    base = load_base(base_path)
    entries = registry.load(models_path)
    config, warnings = render(base, entries, available)
    text = dump(config)
    old = read_text(out_path)
    changed = old != text
    if changed and not dry_run:
        write(out_path, text)
    return {"changed": changed, "warnings": warnings, "diff": diff(old, text), "text": text}
